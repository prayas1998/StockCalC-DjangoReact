create table public.journal_tradejournal (
  id bigint generated by default as identity primary key,
  user_id uuid,
  company_name varchar(255) not null,
  trade_type varchar(20) not null,
  quantity integer not null check (quantity >= 0),
  buy_price numeric(10,2),
  sell_price numeric(10,2),
  stop_loss numeric(10,2),
  target_price numeric(10,2),
  entry_date date not null,
  exit_date date,
  status varchar(20) not null,
  personal_notes text not null,
  created_at timestamptz not null,
  updated_at timestamptz not null,
  direction varchar(10) not null,
  broker varchar(20) not null,
  exchange varchar(10) not null
);
create table public.journal_tradetags (
  id bigint generated by default as identity primary key,
  name varchar(50) not null unique,
  color varchar(7) not null,
  user_id uuid,
  created_at timestamptz not null
);
create table public.journal_tradejournaltags (
  id bigint generated by default as identity primary key,
  trade_id bigint not null references public.journal_tradejournal,
  tag_id bigint not null references public.journal_tradetags
);

